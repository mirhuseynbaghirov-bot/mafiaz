const languageSelect = document.getElementById("languageSelect");
const mobileMenu = document.getElementById("mobileMenu");
const navLinks = document.querySelector(".nav-links");

const modal = document.getElementById("modal");
const modalTitle = document.getElementById("modalTitle");
const modalDescription = document.getElementById("modalDescription");
const modalClose = document.getElementById("modalClose");

let currentLanguage = "az";

function translatePage(language) {
  currentLanguage = translations[language] ? language : "az";

  document.documentElement.lang = currentLanguage;

  document.querySelectorAll("[data-i18n]").forEach(element => {
    const key = element.dataset.i18n;
    const translatedText = translations[currentLanguage][key];

    if (translatedText) {
      element.textContent = translatedText;
    }
  });

  if (languageSelect) {
    languageSelect.value = currentLanguage;
  }
}

function showModal(title, description) {
  if (!modal) return;

  if (modalTitle) modalTitle.textContent = title;
  if (modalDescription) modalDescription.textContent = description;

  modal.classList.add("active");
}

function closeModal() {
  if (modal) modal.classList.remove("active");
}

function message(key) {
  return translations[currentLanguage][key] || translations.az[key];
}

// Language selection
if (languageSelect) {
  languageSelect.addEventListener("change", event => {
    translatePage(event.target.value);
  });
}

// Mobile navigation
if (mobileMenu && navLinks) {
  mobileMenu.addEventListener("click", () => {
    navLinks.classList.toggle("active");
  });
}

document.querySelectorAll(".nav-links a").forEach(link => {
  link.addEventListener("click", () => {
    navLinks?.classList.remove("active");
  });
});

// Close modal
modalClose?.addEventListener("click", closeModal);

modal?.addEventListener("click", event => {
  if (event.target === modal) {
    closeModal();
  }
});

document.addEventListener("keydown", event => {
  if (event.key === "Escape") {
    closeModal();
  }
});

// Play button
document.getElementById("playBtn")?.addEventListener("click", () => {
  showModal(
    message("comingTitle"),
    message("comingDescription")
  );
});

// Create room button
document.getElementById("createBtn")?.addEventListener("click", () => {
  showModal(
    message("comingTitle"),
    message("comingDescription")
  );
});

// Join room button
document.getElementById("joinBtn")?.addEventListener("click", () => {
  const roomCode = document.getElementById("roomCode");
  const code = roomCode?.value.trim() || "";

  if (!code) {
    showModal(message("comingTitle"), message("emptyCode"));
    return;
  }

  if (code.length < 4) {
    showModal(message("comingTitle"), message("invalidCode"));
    return;
  }

  showModal(message("comingTitle"), message("joinLater"));
});

// Login and signup
document.getElementById("loginBtn")?.addEventListener("click", () => {
  showModal(message("comingTitle"), message("comingDescription"));
});

document.getElementById("signupBtn")?.addEventListener("click", () => {
  showModal(message("comingTitle"), message("comingDescription"));
});

// Initial language
translatePage(languageSelect?.value || "az");

console.log("MAFIA website initialized.");
